/** Largura (pt) de um texto em Helvetica no tamanho dado. Letra desconhecida conta como "n". */
export function helveticaWidth(text: string, fontSize: number, bold = false): number {
  const m = bold ? HELVETICA.bold : HELVETICA.regular
  let units = 0
  for (const ch of text) {
    const code = ch.charCodeAt(0)
    units += code >= 32 && code <= 126 ? m.ascii[code - 32] : ((m.extra as Record<string, number>)[ch] ?? m.ascii['n'.charCodeAt(0) - 32])
  }
  return (units / 1000) * fontSize
}
